const HOUR_MS = 3_600_000
const DAY_MS = 86_400_000
const JST_MS = 9 * HOUR_MS

/** 時刻 ms（epoch ミリ秒）が入る JST の暦日の通し番号（1970-01-01 が 0） */
const jstDay = (ms: number) => Math.floor((ms + JST_MS) / DAY_MS)

const HOLIDAY_DAYS: ReadonlySet<number> = new Set(
  JP_HOLIDAYS.map((d) => Date.UTC(Number(d.slice(0, 4)), Number(d.slice(5, 7)) - 1, Number(d.slice(8, 10))) / DAY_MS),
)

/** 一覧が受け持つ最後の日（一覧の最後の年の 12/31）。内閣府の CSV は年ごとにまとめて載るので、最後の年の残りの日は祝日が無い */
export const HOLIDAYS_LAST_DAY = `${JP_HOLIDAYS[JP_HOLIDAYS.length - 1].slice(0, 4)}-12-31`
const LAST_DAY = Date.UTC(Number(HOLIDAYS_LAST_DAY.slice(0, 4)), 11, 31) / DAY_MS

/** 時刻 ms（epoch ミリ秒）が休みの日（JST で土日か祝日）か */
export function isOffAt(ms: number): boolean {
  const day = jstDay(ms)
  // 1970-01-01（通し番号 0）は木曜。0 = 日曜 … 6 = 土曜
  const dow = (((day + 4) % 7) + 7) % 7
  return dow === 0 || dow === 6 || HOLIDAY_DAYS.has(day)
}

/** [t0, t1)（epoch ミリ秒）のうち休みの日の時間の割合。JST の 0 時で切って数える。長さ 0 の区間は t0 が休みの日なら 1 */
export function offFraction(t0: number, t1: number): number {
  if (!(t1 > t0)) return isOffAt(t0) ? 1 : 0
  let off = 0
  let a = t0
  while (a < t1) {
    const nextMidnight = (jstDay(a) + 1) * DAY_MS - JST_MS
    const b = Math.min(t1, nextMidnight)
    if (isOffAt(a)) off += b - a
    a = b
  }
  return off / (t1 - t0)
}

/** 時刻 ms（epoch ミリ秒）の JST の暦日が、祝日の一覧の受け持つ最後の日（HOLIDAYS_LAST_DAY）より後か */
export function beyondHolidayList(ms: number): boolean {
  return jstDay(ms) > LAST_DAY
}
